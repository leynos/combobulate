"""Bind the Kani provenance record to its corpus build inputs and SDK.

The Kani record is regenerated by ``make kani-log-corpus``. These tests require
it to name the manifest, lockfile, harness sources, inventories, and generating
scripts, and to record the child toolchain that compiled the harnesses, so a
premature record cannot pass as bound evidence.
"""

import json
import unittest

from verifier_probe_loader import (
    ROOT,
    load_verifier_probe_support,
)


class KaniSourceBindingTests(unittest.TestCase):
    """Require the Kani record to bind the corpus build inputs and its SDK."""

    _REQUIRED = frozenset({
        'tools/verifier-fixtures/kani-corpus/Cargo.toml',
        'tools/verifier-fixtures/kani-corpus/Cargo.lock',
        'tools/verifier-fixtures/kani-corpus/src/lib.rs',
        'tools/verifier-fixtures/kani-corpus/src/harnesses.rs',
        'tools/verifier-fixtures/kani-corpus/harnesses.json',
        'tools/verifier-fixtures/kani-corpus/kani-list.json',
        'scripts/run_verifier_probes.py',
        'scripts/kani_probe.py',
        'scripts/verifier_probe_support.py',
        'scripts/probe_provenance.py',
    })

    def test_kani_record_binds_its_build_inputs_and_toolchain(self) -> None:
        """A harness verdict must name the manifest, lockfile, and SDK it used."""
        support = load_verifier_probe_support()
        path = ROOT / 'scripts/tests/fixtures/kani_logs/provenance.json'
        record = json.loads(path.read_text(encoding='utf-8'))

        self.assertEqual(
            sorted(self._REQUIRED - record['source_digests'].keys()),
            [],
            'the Kani record must bind the corpus manifest, lockfile, and generators',
        )
        self.assertEqual(
            record.get('toolchain'),
            support.KANI_SDK_TOOLCHAIN,
            'the record must name the SDK toolchain that built the harnesses',
        )
